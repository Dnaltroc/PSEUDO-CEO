/* Regenerates api/_statsui.js (the owner dashboard, served only to a valid key) from src/stats-app.html.
   Run after editing the dashboard:  node dev/gen-statsui.js */
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'src', 'stats-app.html'), 'utf8');
fs.writeFileSync(path.join(root, 'api', '_statsui.js'), '/* Generated by dev/gen-statsui.js from src/stats-app.html. Do not edit by hand. */\nmodule.exports = ' + JSON.stringify(html) + ';\n');
console.log('api/_statsui.js written,', html.length, 'bytes of dashboard');
